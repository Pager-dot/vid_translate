//! Offline eval runner: WAV in, English hypothesis out, no Tauri and no UI.
//!
//! Phase 5 of the JA chunking plan. The point is to make every later change measurable
//! instead of vibes-based: it drives the *real* pipeline components (Vosk → chunker →
//! CTranslate2) over a fixed clip set, so a chunker or model change shows up as a BLEU /
//! chrF / latency delta rather than an impression.
//!
//! Usage:
//!
//!   cargo run --bin ja_eval -- eval/ja/clip01.wav [clip02.wav ...]
//!
//! Input must be 16 kHz mono 16-bit PCM WAV — the same format the live capture path feeds
//! Vosk, so the ASR sees exactly what it sees in production:
//!
//!   ffmpeg -i clip.mp4 -ac 1 -ar 16000 -c:a pcm_s16le eval/ja/clip01.wav
//!
//! Prints one JSON object per clip on stdout (so `eval/run.sh` can collect them) and
//! progress on stderr.

use std::path::Path;
use std::sync::atomic::AtomicBool;
use std::time::Instant;

use vid_translate_lib::chunker::japanese::{Guards, JapaneseChunker};
use vid_translate_lib::chunker::{self, Chunk, ChunkStrategy, FinalOnlyChunker};
use vid_translate_lib::marian::{self, MarianState};
use vid_translate_lib::recognizer::{self, Backend, RecognitionResult};

/// 250ms at 16 kHz — the chunk size the live audio path uses, so the recognizer produces
/// the same number of partials per second as it does in the app.
const SAMPLES_PER_CHUNK: usize = 4000;

/// Minimal 16-bit PCM WAV reader. Deliberately not a dependency: the eval corpus is
/// generated by one documented ffmpeg command, so exactly one format has to be supported,
/// and a strict reader that rejects anything else is more useful than a lenient one.
fn read_wav_16k_mono(path: &Path) -> Result<Vec<i16>, String> {
    let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    if bytes.len() < 44 || &bytes[0..4] != b"RIFF" || &bytes[8..12] != b"WAVE" {
        return Err(format!("{}: not a RIFF/WAVE file", path.display()));
    }

    let u16_at = |i: usize| u16::from_le_bytes([bytes[i], bytes[i + 1]]);
    let u32_at = |i: usize| u32::from_le_bytes([bytes[i], bytes[i + 1], bytes[i + 2], bytes[i + 3]]);

    // Walk the chunk list rather than assuming a 44-byte header: ffmpeg writes a LIST
    // chunk before `data` often enough that assuming would silently read metadata as audio.
    let mut pos = 12;
    let mut fmt: Option<(u16, u16, u32, u16)> = None;
    while pos + 8 <= bytes.len() {
        let id = &bytes[pos..pos + 4];
        let size = u32_at(pos + 4) as usize;
        let body = pos + 8;
        match id {
            b"fmt " if body + 16 <= bytes.len() => {
                fmt = Some((u16_at(body), u16_at(body + 2), u32_at(body + 4), u16_at(body + 14)));
            }
            b"data" => {
                let (format, channels, rate, bits) =
                    fmt.ok_or_else(|| format!("{}: data before fmt", path.display()))?;
                if format != 1 || channels != 1 || rate != 16000 || bits != 16 {
                    return Err(format!(
                        "{}: need 16 kHz mono 16-bit PCM, got format={format} ch={channels} \
                         rate={rate} bits={bits} — re-encode with: \
                         ffmpeg -i <in> -ac 1 -ar 16000 -c:a pcm_s16le <out>.wav",
                        path.display()
                    ));
                }
                let end = (body + size).min(bytes.len());
                return Ok(bytes[body..end]
                    .chunks_exact(2)
                    .map(|p| i16::from_le_bytes([p[0], p[1]]))
                    .collect());
            }
            _ => {}
        }
        // Chunks are word-aligned, so an odd size is followed by a pad byte.
        pos = body + size + (size & 1);
    }
    Err(format!("{}: no data chunk", path.display()))
}

/// Which recognizer to decode with. Japanese ships on Whisper now, so that is the default
/// here too — `VID_TRANSLATE_EVAL_RECOGNIZER=vosk` keeps the old one reachable for
/// comparison, which is the whole reason the backends share an interface.
fn pick_backend() -> (Backend, std::path::PathBuf) {
    let vosk = dirs::data_local_dir()
        .unwrap_or_else(|| ".".into())
        .join("vid_translate")
        .join("vosk-model-ja");
    if std::env::var("VID_TRANSLATE_EVAL_RECOGNIZER").as_deref() == Ok("vosk") {
        return (Backend::Vosk, vosk);
    }
    let whisper = std::env::var_os("VID_TRANSLATE_WHISPER_MODEL")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| {
            dirs::data_local_dir()
                .unwrap_or_else(|| ".".into())
                .join("vid_translate")
                .join("ggml-small.bin")
        });
    (Backend::Whisper("ja"), whisper)
}

/// The plan asks for the pre-change baseline to be recorded before the clause chunker is
/// merged. It already is merged, so the baseline is reproduced here instead:
/// `VID_TRANSLATE_EVAL_CHUNKER=final-only` runs the old translate-on-`Final`-only
/// behaviour, letting both numbers be measured from the same build.
///
/// Deliberately read here and not in `chunker::for_language`: this is a measurement knob,
/// and an env var that silently changes what the shipped app does is a different and worse
/// thing than one that changes what the eval runner does.
fn pick_chunker() -> Box<dyn ChunkStrategy> {
    if let Ok("final-only") = std::env::var("VID_TRANSLATE_EVAL_CHUNKER").as_deref() {
        return Box::new(FinalOnlyChunker::default());
    }
    // The three guards are swept rather than argued about: VID_TRANSLATE_EVAL_GUARDS is
    // "min,max,wait_ms". Unset means production defaults.
    match std::env::var("VID_TRANSLATE_EVAL_GUARDS") {
        Ok(spec) => {
            let parts: Vec<&str> = spec.split(',').collect();
            let d = Guards::default();
            let guards = Guards {
                min_chunk_chars: parts.first().and_then(|v| v.parse().ok()).unwrap_or(d.min_chunk_chars),
                max_chunk_chars: parts.get(1).and_then(|v| v.parse().ok()).unwrap_or(d.max_chunk_chars),
                max_wait_ms: parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(d.max_wait_ms),
            };
            eprintln!("[ja_eval] guards {guards:?}");
            Box::new(JapaneseChunker::with_guards(guards))
        }
        Err(_) => chunker::for_language("ja", true),
    }
}

/// Real-time mode: feed the recognizer at the pace the audio actually plays, run the
/// chunk and tail translators on their own threads as `run_translated_pipeline` does, and
/// record when each piece of English would have reached the screen.
///
/// This is the only way to get a latency number that means anything. In batch mode the
/// whole clip is handed over at once, so every chunk is cut within a second or two and
/// then queues behind a serial translate loop — a "latency" measured there is the backlog
/// of that burst and nothing a user would ever experience.
///
/// Because the feed is paced, audio position and wall clock advance together, so for any
/// event at wall time W reflecting audio up to position P, the user-visible delay is W - P.
mod realtime {
    use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
    use std::sync::Mutex;
    use std::time::{Duration, Instant};

    use vid_translate_lib::chunker::ChunkStrategy;
    use vid_translate_lib::marian::{self, MarianState};
    use vid_translate_lib::recognizer::{self, RecognitionResult};

    use super::{p95, SAMPLES_PER_CHUNK};

    /// Mirrors the app: one translation per 300ms for the in-progress tail.
    const TAIL_DEBOUNCE_MS: u64 = 300;

    #[derive(Default)]
    pub struct Latencies {
        /// Last word of a clause spoken -> its finished English available. What the user
        /// waits once they have stopped saying the clause.
        pub confirmed_tail: Vec<u128>,
        /// First word of a clause spoken -> its finished English available. The whole wait
        /// for a committed line, which includes however long the clause took to say.
        pub confirmed_head: Vec<u128>,
        /// A word spoken -> the live provisional line reflecting it. The number that
        /// decides whether the app feels responsive.
        pub live_line: Vec<u128>,
        /// Same updates, timed from the *oldest* word each one newly covers — the worst
        /// case any word experiences. The true per-word figure lies between this and
        /// `live_line`.
        pub live_line_oldest: Vec<u128>,
        /// Audio position already reflected on the live line.
        pub covered_ms: u64,
        /// Translations that returned nothing or an error. Any non-zero value invalidates
        /// the latency figures: a translation that never happened looks instantaneous.
        pub failed: usize,
    }

    pub fn run(
        samples: Vec<i16>,
        backend: super::Backend,
        model_path: &str,
        state: &MarianState,
        chunker: &mut dyn ChunkStrategy,
    ) -> Result<Latencies, String> {
        let fed_samples = AtomicU64::new(0);
        let lat = Mutex::new(Latencies::default());
        // One clock for everything, so "audio position" and "now" are the same scale.
        let clock = Instant::now();

        // Explicit borrows, so each worker can take ownership of its receiver with `move`
        // while still sharing the clock, the counter and the latency table.
        let lat_ref = &lat;
        let fed_ref = &fed_samples;
        let clock_ref = &clock;

        std::thread::scope(|scope| -> Result<(), String> {
            let (tx_audio, rx_audio) = std::sync::mpsc::channel();
            let (tx_chunk, rx_chunk) = std::sync::mpsc::channel::<(String, u64, u64)>();
            let (tx_tail, rx_tail) = std::sync::mpsc::channel::<(String, u64)>();

            // Feeder: 250ms of audio every 250ms of wall clock, as live capture does.
            scope.spawn(move || {
                for (i, block) in samples.chunks(SAMPLES_PER_CHUNK).enumerate() {
                    let due = Duration::from_millis((i as u64) * 250);
                    if let Some(wait) = due.checked_sub(clock_ref.elapsed()) {
                        std::thread::sleep(wait);
                    }
                    if tx_audio.send(block.to_vec()).is_err() {
                        return;
                    }
                    fed_ref.fetch_add(block.len() as u64, Ordering::Relaxed);
                }
            });

            // Chunk translator, on its own thread as run_translated_pipeline does.
            scope.spawn(move || {
                let stop = AtomicBool::new(false);
                for (text, head_ms, tail_ms) in rx_chunk {
                    let en = marian::translate_local_blocking("ja", &text, &stop, state, |_| {});
                    if en.is_empty() || en.starts_with("[translation error") {
                        lat_ref.lock().unwrap().failed += 1;
                        eprintln!("[realtime] chunk translation produced nothing: {en:?}");
                    }
                    let now = clock_ref.elapsed().as_millis() as u64;
                    let mut l = lat_ref.lock().unwrap();
                    l.confirmed_tail.push(now.saturating_sub(tail_ms) as u128);
                    l.confirmed_head.push(now.saturating_sub(head_ms) as u128);
                }
            });

            // Tail translator: debounced, coalescing to the newest tail, as in the app.
            scope.spawn(move || {
                let stop = AtomicBool::new(false);
                while let Ok(mut latest) = rx_tail.recv() {
                    let deadline = Instant::now() + Duration::from_millis(TAIL_DEBOUNCE_MS);
                    loop {
                        let Some(rem) = deadline.checked_duration_since(Instant::now()) else {
                            break;
                        };
                        match rx_tail.recv_timeout(rem) {
                            Ok(newer) => latest = newer,
                            Err(std::sync::mpsc::RecvTimeoutError::Timeout) => break,
                            Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => return,
                        }
                    }
                    let (text, at_ms) = latest;
                    let en = marian::translate_local_blocking("ja", &text, &stop, state, |_| {});
                    let now = clock_ref.elapsed().as_millis() as u64;
                    let mut l = lat_ref.lock().unwrap();
                    if en.is_empty() || en.starts_with("[translation error") {
                        l.failed += 1;
                    }
                    // This update covers the speech between the previous update and `at_ms`.
                    // The newest word in it waited `now - at_ms`; the oldest waited
                    // `now - covered`. Reporting only the former — which is what the first
                    // version of this did — flatters the result to roughly the MT time,
                    // because the debounce keeps replacing the pending tail with a newer
                    // one and so keeps moving the start of the interval forward.
                    let covered = l.covered_ms;
                    l.live_line.push(now.saturating_sub(at_ms) as u128);
                    l.live_line_oldest.push(now.saturating_sub(covered) as u128);
                    l.covered_ms = at_ms;
                }
            });

            // The recognizer runs on this thread. Its closure borrows the senders, so it
            // lives in an inner scope and the senders are dropped after it — which is what
            // ends the two translator threads.
            {
                // Audio position at which the current chunk's first character was spoken.
                let mut head_ms = 0u64;
                // recognizer::run invokes this closure once per fed block, so after n
                // calls the recognizer has heard n * 250ms of audio. Derived from the call
                // count rather than the feeder's atomic, which races with it.
                let mut blocks = 0u64;
                recognizer::run(backend, model_path, rx_audio, || {}, |ev| {
                    blocks += 1;
                    // Everything in this block had finished being spoken by here.
                    let pos = blocks * 250;
                    match ev {
                        RecognitionResult::Partial(text) => {
                            for c in chunker.push_partial(&text) {
                                let _ = tx_chunk.send((c.text, head_ms, pos));
                                head_ms = pos;
                            }
                            let tail = chunker.pending_tail();
                            if !tail.is_empty() {
                                let _ = tx_tail.send((tail, pos));
                            }
                        }
                        RecognitionResult::Final(text) => {
                            for c in chunker.flush(&text) {
                                let _ = tx_chunk.send((c.text, head_ms, pos));
                                head_ms = pos;
                            }
                        }
                        RecognitionResult::Silent => {}
                    }
                })?;
            }
            Ok(())
        })?;

        Ok(lat.into_inner().unwrap())
    }

    pub fn report(l: &Latencies) {
        if l.failed > 0 {
            eprintln!("  !! {} translation(s) produced nothing — latencies below are invalid", l.failed);
        }
        for (name, v) in [
            ("live line, newest word in the update (best case)", &l.live_line),
            ("live line, oldest word in the update (worst case)", &l.live_line_oldest),
            ("confirmed line, from last word of clause", &l.confirmed_tail),
            ("confirmed line, from first word of clause", &l.confirmed_head),
        ] {
            if v.is_empty() {
                continue;
            }
            let mean = v.iter().sum::<u128>() / v.len() as u128;
            eprintln!(
                "  {name:48}  n={:4}  mean {:>6}ms  p95 {:>6}ms",
                v.len(),
                mean,
                p95(v.clone())
            );
        }
    }
}

struct ClipResult {
    chunks: Vec<Chunk>,
    /// English for each chunk, index-aligned with `chunks`.
    english_per_chunk: Vec<String>,
    hypothesis: String,
    /// Per-chunk translate time. Not end-to-end latency — see the note at the call site.
    latencies_ms: Vec<u128>,
    total_ms: u128,
}

/// Runs already-transcribed Japanese through the rest of the pipeline: chunker, then MT.
///
/// This is how a different recognizer gets compared against Vosk on equal terms. Whisper is
/// not streaming — it emits finished, punctuated segments rather than a growing partial — so
/// each line is fed as its own ASR final, which is the honest analogue of what the live
/// pipeline would see. Everything downstream is the shipped code.
fn run_text_clip(path: &Path, state: &MarianState) -> Result<ClipResult, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let stop_flag = AtomicBool::new(false);
    let started = Instant::now();

    let mut chunker = pick_chunker();
    let mut chunks: Vec<Chunk> = Vec::new();
    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        chunks.extend(chunker.flush(line.trim()));
    }

    let mut pieces = Vec::new();
    let mut latencies_ms = Vec::new();
    let mut english_per_chunk = Vec::new();
    for chunk in &chunks {
        let t = Instant::now();
        let english =
            marian::translate_local_blocking("ja", &chunk.text, &stop_flag, state, |_| {});
        latencies_ms.push(t.elapsed().as_millis());
        english_per_chunk.push(english.clone());
        if !english.is_empty() {
            pieces.push(english);
        }
    }

    Ok(ClipResult {
        chunks,
        english_per_chunk,
        hypothesis: pieces.join(" "),
        latencies_ms,
        total_ms: started.elapsed().as_millis(),
    })
}

fn run_clip(
    path: &Path,
    backend: Backend,
    model_path: &str,
    state: &MarianState,
) -> Result<ClipResult, String> {
    let samples = read_wav_16k_mono(path)?;
    let stop_flag = AtomicBool::new(false);
    let started = Instant::now();

    // Feed the whole clip up front: `recognizer::run` consumes the channel until it is
    // closed, and offline we want it to run as fast as the CPU allows, not in real time.
    let (tx, rx) = std::sync::mpsc::channel();
    for block in samples.chunks(SAMPLES_PER_CHUNK) {
        let _ = tx.send(block.to_vec());
    }
    drop(tx);

    let mut chunker = pick_chunker();
    let mut chunks: Vec<Chunk> = Vec::new();
    // When each chunk was cut. Kept for ordering only: see the note on `latencies_ms`.
    let mut cut_at: Vec<Instant> = Vec::new();

    recognizer::run(backend, model_path, rx, || {}, |ev| match ev {
        RecognitionResult::Partial(text) => {
            for c in chunker.push_partial(&text) {
                chunks.push(c);
                cut_at.push(Instant::now());
            }
        }
        RecognitionResult::Final(text) => {
            for c in chunker.flush(&text) {
                chunks.push(c);
                cut_at.push(Instant::now());
            }
        }
        RecognitionResult::Silent => {}
    })?;

    let mut pieces = Vec::new();
    let mut latencies_ms = Vec::new();
    // Per-chunk English, kept beside its source chunk. This is what makes the "was it bad
    // ASR or bad MT?" question answerable from the output alone: a chunk whose Japanese is
    // already wrong tells you nothing about the model, and the two can only be told apart
    // when they sit side by side.
    let mut english_per_chunk = Vec::new();
    for (chunk, _cut) in chunks.iter().zip(&cut_at) {
        // Translate time per chunk, not cut-to-shown. Offline the entire clip is fed to the
        // recognizer at once, so every chunk is cut within a second or two and then waits
        // its turn in a serial translate loop: a cut-to-shown number here measures the
        // backlog of that burst, not anything a user would experience. End-to-end latency
        // needs the audio paced in real time, which this harness deliberately does not do.
        let t = Instant::now();
        let english =
            marian::translate_local_blocking("ja", &chunk.text, &stop_flag, state, |_| {});
        latencies_ms.push(t.elapsed().as_millis());
        english_per_chunk.push(english.clone());
        if !english.is_empty() {
            pieces.push(english);
        }
    }

    Ok(ClipResult {
        chunks,
        english_per_chunk,
        hypothesis: pieces.join(" "),
        latencies_ms,
        total_ms: started.elapsed().as_millis(),
    })
}

fn p95(mut v: Vec<u128>) -> u128 {
    if v.is_empty() {
        return 0;
    }
    v.sort_unstable();
    // Nearest-rank p95: with the 20-30 clips this harness is sized for, interpolating
    // between order statistics implies a precision the sample does not have.
    v[((v.len() as f64 * 0.95).ceil() as usize).saturating_sub(1).min(v.len() - 1)]
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.is_empty() {
        eprintln!("usage: ja_eval <clip.wav|transcript.txt> [more ...]");
        eprintln!("  a .txt input is Japanese already transcribed by another recognizer,");
        eprintln!("  one ASR final per line — for comparing recognizers on equal terms");
        eprintln!("  VID_TRANSLATE_JA_MODEL_DIR overrides the MT model directory (Phase 4 A/B)");
        eprintln!("  VID_TRANSLATE_EVAL_CHUNKER=final-only reproduces the pre-chunker baseline");
        eprintln!("  VID_TRANSLATE_EVAL_REALTIME=1 paces the audio and reports real latency");
        std::process::exit(2);
    }

    // Real-time mode plays the clip at its true pace, so a 36-minute clip takes 36 minutes.
    // It is the only mode whose latency numbers mean anything; see `mod realtime`.
    let realtime = std::env::var("VID_TRANSLATE_EVAL_REALTIME").is_ok_and(|v| v == "1");
    let all_text = args
        .iter()
        .all(|a| Path::new(a).extension().and_then(|e| e.to_str()) == Some("txt"));
    let (backend, model) = pick_backend();
    if !all_text && !model.exists() {
        eprintln!(
            "no {backend:?} model at {} — start the app once in JA mode to download it, or \
             point VID_TRANSLATE_WHISPER_MODEL at a ggml file",
            model.display()
        );
        std::process::exit(1);
    }
    eprintln!("[ja_eval] recognizer: {backend:?}");
    let model = model.to_string_lossy().to_string();

    // One MarianState for the whole run so the model is loaded from disk once.
    let state = MarianState::default();
    let mut all_latencies = Vec::new();
    let mut failures = 0;

    for arg in &args {
        let path = Path::new(arg);
        eprintln!("[ja_eval] {}", path.display());
        if realtime {
            match read_wav_16k_mono(path).and_then(|samples| {
                let mut chunker = pick_chunker();
                realtime::run(samples, backend, &model, &state, chunker.as_mut())
            }) {
                Ok(l) => {
                    eprintln!("[ja_eval] real-time latency for {}:", path.display());
                    realtime::report(&l);
                }
                Err(e) => {
                    failures += 1;
                    eprintln!("[ja_eval] FAILED {e}");
                }
            }
            continue;
        }
        let outcome = if path.extension().and_then(|e| e.to_str()) == Some("txt") {
            run_text_clip(path, &state)
        } else {
            run_clip(path, backend, &model, &state)
        };
        match outcome {
            Ok(r) => {
                all_latencies.extend(r.latencies_ms.iter().copied());
                let mean = if r.latencies_ms.is_empty() {
                    0
                } else {
                    r.latencies_ms.iter().sum::<u128>() / r.latencies_ms.len() as u128
                };
                let out = serde_json::json!({
                    "clip": path.file_name().and_then(|s| s.to_str()).unwrap_or(arg),
                    "hypothesis": r.hypothesis,
                    "chunks": r.chunks.iter().zip(&r.english_per_chunk).map(|(c, en)| serde_json::json!({
                        "source": c.text,
                        "english": en,
                        "boundary_confident": c.boundary_confident,
                    })).collect::<Vec<_>>(),
                    "chunk_count": r.chunks.len(),
                    "forced_cuts": r.chunks.iter().filter(|c| !c.boundary_confident).count(),
                    "mt_mean_ms": mean,
                    "mt_p95_ms": p95(r.latencies_ms),
                    "total_ms": r.total_ms,
                });
                println!("{out}");
            }
            Err(e) => {
                failures += 1;
                eprintln!("[ja_eval] FAILED {e}");
            }
        }
    }

    let n = all_latencies.len();
    eprintln!(
        "[ja_eval] {} clip(s), {} chunk(s), MT mean {}ms, MT p95 {}ms{}",
        args.len() - failures,
        n,
        if n == 0 { 0 } else { all_latencies.iter().sum::<u128>() / n as u128 },
        p95(all_latencies),
        if failures > 0 { format!(", {failures} failed") } else { String::new() },
    );
    // Before any exit path: the cached model holds Metal resources that ggml's global
    // destructor insists have been released. Without this the process aborts after doing
    // all its work correctly.
    vid_translate_lib::recognizer::whisper::unload_all();

    if failures > 0 {
        std::process::exit(1);
    }
}
